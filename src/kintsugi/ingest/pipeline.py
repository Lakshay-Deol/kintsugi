"""Ingestion pipeline: PDF -> chunks -> embeddings -> Atlas.
Runs locally only. Never runs on Render.
Writes evidence/phase1_chunks.json on completion.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

from kintsugi.config import get_config
from kintsugi.db import get_collection
from kintsugi.ingest.chunker import chunk_pdf
from kintsugi.ingest.embedder import embed_texts

log = logging.getLogger(__name__)


def ingest_manual(
    pdf_path: Path,
    manual_id: str,
    brand: str,
    model: str,
    *,
    batch_size: int = 32,
    dry_run: bool = False,
) -> dict[str, Any]:
    """
    Full ingest: parse PDF -> embed -> upsert to Atlas.
    Returns ingestion stats.
    """
    log.info("Ingesting %s (manual_id=%s brand=%s model=%s)", pdf_path.name, manual_id, brand, model)

    chunks = chunk_pdf(pdf_path, manual_id, brand, model)
    total = len(chunks)
    log.info("  Chunked: %d chunks", total)

    if dry_run:
        log.info("  Dry run — skipping embed and Atlas upsert")
        return {"manual_id": manual_id, "chunks": total, "upserted": 0, "dry_run": True}

    # Embed in batches
    texts = [c["text"] for c in chunks]
    for i in range(0, total, batch_size):
        batch = texts[i : i + batch_size]
        embeddings = embed_texts(batch)
        for chunk, emb in zip(chunks[i : i + batch_size], embeddings):
            chunk["embedding"] = emb
        log.info("  Embedded batch %d/%d", min(i + batch_size, total), total)

    # Upsert to Atlas
    cfg = get_config()
    col = get_collection(cfg.chunks_collection)
    upserted = 0
    for i in range(0, total, batch_size):
        batch = chunks[i : i + batch_size]
        for chunk in batch:
            col.replace_one({"_id": chunk["_id"]}, chunk, upsert=True)
            upserted += 1

    # Register manual in manuals collection
    manuals_col = get_collection(cfg.manuals_collection)
    manuals_col.replace_one(
        {"_id": manual_id},
        {
            "_id": manual_id,
            "manual_id": manual_id,
            "brand": brand,
            "model": model,
            "source_file": pdf_path.name,
            "chunk_count": total,
        },
        upsert=True,
    )

    log.info("  Upserted %d chunks to Atlas", upserted)
    return {"manual_id": manual_id, "chunks": total, "upserted": upserted, "dry_run": False}


def write_phase1_evidence(stats: list[dict[str, Any]], evidence_dir: Path) -> None:
    """Write evidence/phase1_chunks.json — generated by ingest script, never hand-edited."""
    evidence_dir.mkdir(parents=True, exist_ok=True)
    out = evidence_dir / "phase1_chunks.json"
    out.write_text(json.dumps(stats, indent=2))
    log.info("Phase 1 evidence written to %s", out)
